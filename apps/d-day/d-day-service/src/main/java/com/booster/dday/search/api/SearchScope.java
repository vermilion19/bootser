package com.booster.dday.search.api;

/**
 * 이 소스가 <b>누구의 자료</b>를 들고 있나.
 *
 * <p>SPEC §E-2 가 «한 응답에 공개 자료와 남의 것이 아닌 자료가 섞인다» 고 한 것이
 * 이 두 값이다. <b>이 서비스에서 캐시 전략이 갈라지는 유일한 지점</b>이기도 하다.
 *
 * <p>값을 두는 목적이 분류가 아니라 <b>차단</b>이다. {@link #PERSONAL} 소스는
 * 로그인하지 않은 요청에서 <b>불리지도 않는다</b> — 「빈 결과를 돌려준다」가 아니라
 * 「호출 자체가 없다」. 거르는 코드를 한 군데서 빠뜨리는 날 남의 것이 열리는데,
 * 부르지 않으면 빠뜨릴 자리가 없다.
 */
public enum SearchScope {

    /** 누구나 본다 */
    PUBLIC,

    /** 주인만 본다. <b>로그인 없이는 부르지 않는다</b> */
    PERSONAL
}
